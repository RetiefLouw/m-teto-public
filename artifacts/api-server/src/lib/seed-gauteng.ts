export async function seedGauteng() {
  // Check if already seeded (look for providers with area set — only the Gauteng comprehensive seed sets this)
  const existing = await db
    .select({ id: providersTable.id })
    .from(providersTable)
    .where(and(eq(providersTable.province, "Gauteng"), isNotNull(providersTable.area)))
    .limit(1);

  if (existing.length > 0) {
    console.log("⏭️  Gauteng providers already seeded — skipping");
    return;
  }

  console.log(`🌍 Seeding ${GAUTENG_PROVIDERS.length} Gauteng service providers...`);

  let providerCount = 0;
  let officialCount = 0;

  for (const seed of GAUTENG_PROVIDERS) {
    const { officials: officialSeeds, ...providerData } = seed;

    const [inserted] = await db
      .insert(providersTable)
      .values(providerData)
      .returning({ id: providersTable.id });

    providerCount++;

    if (officialSeeds && officialSeeds.length > 0) {
      await db.insert(officialsTable).values(
        officialSeeds.map((o) => ({
          providerId: inserted.id,
          name: o.name,
          title: o.title,
          unit: o.unit ?? null,
          phone: o.phone ?? null,
          email: o.email ?? null,
          isPrimary: o.isPrimary ?? false,
        })),
      );
      officialCount += officialSeeds.length;
    }
  }

  console.log(
    `✅ Gauteng seed complete: ${providerCount} providers, ${officialCount} officials`,
  );
}
